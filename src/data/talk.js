function partyTalkLine(id) {
  const t = PARTY_TALK[id];
  if (!t) return null;
  const map = Field.map;
  if (map && map.kind === 'dungeon' && t.dungeon && Util.chance(0.5)) return t.dungeon;
  const p = Game.progress();
  let best = null;
  for (const k of Object.keys(t).filter((k) => !isNaN(k)).map(Number).sort((a, b) => a - b)) if (k <= p) best = t[k];
  return best || t.dungeon;
}
